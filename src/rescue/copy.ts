export const rescueCopy = { ro, en };

export type RescueLocale = keyof typeof rescueCopy;
export type RescueKey = keyof typeof ro;

function needsDe(n: number): boolean {
  if (!Number.isFinite(n)) return false;
  const whole = Math.abs(Math.trunc(n));
  if (whole === 0 || whole === 1) return false;
  const lastTwo = whole % 100;
  return !(lastTwo >= 1 && lastTwo <= 19);
}

export function rescueT(
  locale: RescueLocale,
  key: RescueKey,
  params?: Record<string, string | number>
): string {
  let str: string = rescueCopy[locale][key];
  if (!params) return str;
  const count = params.count;
  const withDe = typeof count === 'number'
    ? { ...params, countDe: locale === 'ro' && needsDe(count) ? `${count} de` : String(count) }
    : params;
  for (const [name, value] of Object.entries(withDe)) {
    str = str.split(`{${name}}`).join(String(value));
  }
  return str;
}
